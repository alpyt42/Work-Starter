#!/usr/bin/env python3
"""Install the own skills that must be real copies in the agent discovery directories.

A brain skill whose folder holds an empty `.install-as-copy` file is copied from
`<brain>/skills/<name>` to `.agents/skills/<name>` and `.claude/skills/<name>`
(a copy keeps its own relative paths and survives a moved brain). Each copy carries
a generated marker file; copies without a matching enabled skill are removed, and
a directory without the marker is never touched. Other own skills are symbolic
links, handled by link-skills.sh.

`--check` changes nothing and fails when a copy is missing, stale or obsolete.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

from work_config import ROOT, ConfigError, enabled_own, rel, resolve

DESTINATIONS = (ROOT / ".agents/skills", ROOT / ".claude/skills")
MARKER = ".generated-from-brain-skill"
CACHES = ("__pycache__", "*.pyc", ".DS_Store")
IGNORED = shutil.ignore_patterns(*CACHES)


def files(directory: Path) -> dict[str, bytes]:
    """Content of a skill folder, without the generated marker and caches."""
    kept = {}
    for path in directory.rglob("*"):
        relative = path.relative_to(directory)
        if path.is_file() and path.name != MARKER and not IGNORED(str(directory), list(relative.parts)):
            kept[relative.as_posix()] = path.read_bytes()
    return kept


def marker_text(name: str, skill: dict) -> str:
    return f"Generated by tools/machine/sync-house-skills.py from {skill['brain']}/skills/{name}\n"


def is_current(destination: Path, name: str, skill: dict) -> bool:
    marker = destination / MARKER
    return (
        destination.is_dir()
        and not destination.is_symlink()
        and marker.is_file()
        and marker.read_text(encoding="utf-8") == marker_text(name, skill)
        and not any(path.is_symlink() for path in destination.rglob("*"))
        and files(destination) == files(skill["path"])
    )


def is_managed_link(path: Path, name: str) -> bool:
    return path.is_symlink() and re.fullmatch(rf"\.\./\.\./brain(-[a-z0-9][a-z0-9-]*)?/skills/{re.escape(name)}", str(path.readlink())) is not None


def sync(copies: dict[str, dict], check: bool) -> list[str]:
    problems: list[str] = []
    for name, skill in copies.items():
        if any(path.is_symlink() for path in skill["path"].rglob("*")):
            raise SystemExit(f"{rel(skill['path'])} contains a symbolic link: a skill installed as a copy cannot")
    for root in DESTINATIONS:
        if root.is_dir():
            for path in sorted(root.iterdir()):
                if path.name not in copies and path.is_dir() and not path.is_symlink() and (path / MARKER).is_file():
                    if check:
                        problems.append(f"Obsolete generated skill copy: {rel(path)}")
                    else:
                        shutil.rmtree(path)
        for name, skill in copies.items():
            destination = root / name
            if check:
                if not is_current(destination, name, skill):
                    problems.append(f"Generated skill copy is missing or stale: {rel(destination)}")
                continue
            if is_current(destination, name, skill):
                continue
            if destination.is_symlink():
                if not is_managed_link(destination, name):
                    raise SystemExit(f"Refusing to replace an unmanaged symbolic link: {rel(destination)}")
                destination.unlink()
            elif destination.exists():
                if not destination.is_dir() or not (destination / MARKER).is_file():
                    raise SystemExit(f"Refusing to replace a non-generated path: {rel(destination)}")
                shutil.rmtree(destination)
            root.mkdir(parents=True, exist_ok=True)
            shutil.copytree(skill["path"], destination, ignore=IGNORED)
            (destination / MARKER).write_text(marker_text(name, skill), encoding="utf-8")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="verify the generated copies without changing anything")
    args = parser.parse_args()
    try:
        copies = {name: skill for name, skill in enabled_own(resolve()).items() if skill["mode"] == "copy"}
    except ConfigError as error:
        print(f"work config error: {error}", file=sys.stderr)
        return 1
    problems = sync(copies, args.check)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    names = ", ".join(copies) or "none"
    print(f"Skill copies OK ({names})" if args.check else f"Skill copies updated ({names})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
